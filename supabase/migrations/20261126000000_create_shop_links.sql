-- 실물 칠교 구매처 링크
--
-- PDF 를 뽑는 사람은 이미 종이로 만들 생각이다. 가위질이 번거로우면 실물을 산다.
-- 그 흐름에 맞춰 구매처를 모아 보여주고, 운영자가 admin 에서 직접 관리한다.
--
-- 새 테이블이라 배포본에 영향이 없다. 지금 적용해도 안전하다.

CREATE TABLE IF NOT EXISTS public.shop_links (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text NOT NULL,
  url         text NOT NULL,
  -- 쇼핑몰 로고. R2 경로(shop/logo-...png) 또는 https 절대 주소.
  -- 비어 있으면 화면에서 이름 첫 글자로 대체한다
  logo_url    text,
  description text,
  -- 제휴 링크 여부. true 면 화면에 경제적 이해관계 고지를 함께 띄운다
  is_affiliate boolean NOT NULL DEFAULT false,
  is_active   boolean NOT NULL DEFAULT true,
  sort_order  integer NOT NULL DEFAULT 0,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  deleted_at  timestamptz
);

-- 길이 제한으로 목록 레이아웃 보호
ALTER TABLE public.shop_links
  DROP CONSTRAINT IF EXISTS shop_links_name_length_check;
ALTER TABLE public.shop_links
  ADD CONSTRAINT shop_links_name_length_check
  CHECK (char_length(name) BETWEEN 1 AND 40);

ALTER TABLE public.shop_links
  DROP CONSTRAINT IF EXISTS shop_links_description_length_check;
ALTER TABLE public.shop_links
  ADD CONSTRAINT shop_links_description_length_check
  CHECK (description IS NULL OR char_length(description) <= 120);

-- https 만 허용. javascript: 같은 스킴을 막는 동시에, http 링크가
-- https 로 서비스되는 페이지에서 혼합 콘텐츠로 차단되는 것도 함께 막는다.
ALTER TABLE public.shop_links
  DROP CONSTRAINT IF EXISTS shop_links_url_scheme_check;
ALTER TABLE public.shop_links
  ADD CONSTRAINT shop_links_url_scheme_check
  CHECK (url ~* '^https://');

-- 로고는 R2 에 올린 상대 경로이거나 외부 절대 주소다.
-- 상대 경로에는 콜론이 없으므로, 콜론이 있으면 https 만 허용해
-- javascript: · data: · http: 를 막는다.
ALTER TABLE public.shop_links
  DROP CONSTRAINT IF EXISTS shop_links_logo_url_scheme_check;
ALTER TABLE public.shop_links
  ADD CONSTRAINT shop_links_logo_url_scheme_check
  CHECK (logo_url IS NULL OR logo_url ~* '^https://' OR logo_url !~ ':');

-- 목록은 항상 노출 여부 + 정렬순으로 읽는다
CREATE INDEX IF NOT EXISTS shop_links_active_order_idx
  ON public.shop_links (is_active, sort_order, id)
  WHERE deleted_at IS NULL;

ALTER TABLE public.shop_links ENABLE ROW LEVEL SECURITY;

-- 읽기: 누구나, 단 노출 중이고 삭제되지 않은 것만
DROP POLICY IF EXISTS "shop_links_select_active" ON public.shop_links;
CREATE POLICY "shop_links_select_active"
  ON public.shop_links FOR SELECT TO anon, authenticated
  USING (is_active AND deleted_at IS NULL);

-- 관리자는 전부 읽는다 (admin 목록에서 비노출 항목도 보여야 한다)
DROP POLICY IF EXISTS "shop_links_select_admin" ON public.shop_links;
CREATE POLICY "shop_links_select_admin"
  ON public.shop_links FOR SELECT TO authenticated
  USING (public.is_admin(auth.uid()));

-- 쓰기: 관리자만
DROP POLICY IF EXISTS "shop_links_insert_admin" ON public.shop_links;
CREATE POLICY "shop_links_insert_admin"
  ON public.shop_links FOR INSERT TO authenticated
  WITH CHECK (public.is_admin(auth.uid()));

DROP POLICY IF EXISTS "shop_links_update_admin" ON public.shop_links;
CREATE POLICY "shop_links_update_admin"
  ON public.shop_links FOR UPDATE TO authenticated
  USING (public.is_admin(auth.uid()))
  WITH CHECK (public.is_admin(auth.uid()));

COMMENT ON COLUMN public.shop_links.logo_url IS 'R2 경로 또는 https 절대 주소. NULL 이면 이름 첫 글자로 대체.';
COMMENT ON COLUMN public.shop_links.is_affiliate IS '제휴 링크 여부. true 면 경제적 이해관계 고지를 함께 노출한다.';
COMMENT ON COLUMN public.shop_links.sort_order IS '노출 순서. 작을수록 위.';
COMMENT ON COLUMN public.shop_links.url IS '구매처 주소. https 만 허용한다.';
